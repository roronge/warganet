-- Kampung Mini: jalankan sekali di Supabase Dashboard > SQL Editor.
-- Tabel warga: satu baris per akun Auth, satu nama warga per kampung.
create table if not exists public.warga (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 3 and 16),
  joined timestamptz not null default now()
);

create unique index if not exists warga_name_unique_lower
  on public.warga (lower(name));

create table if not exists public.chat (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.warga(id) on delete cascade,
  text text not null check (char_length(trim(text)) between 1 and 120),
  ts timestamptz not null default now()
);

create index if not exists chat_ts_idx on public.chat (ts desc);

alter table public.warga enable row level security;
alter table public.chat enable row level security;

-- Peta dan daftar warga dapat dibaca publik; hanya pemilik akun boleh membuat KTP.
drop policy if exists "Warga can be read by everyone" on public.warga;
create policy "Warga can be read by everyone"
  on public.warga for select to anon, authenticated using (true);

drop policy if exists "Users can create their own warga profile" on public.warga;
create policy "Users can create their own warga profile"
  on public.warga for insert to authenticated
  with check (auth.uid() = id);

-- Chat dapat dibaca publik, tetapi hanya warga yang sudah login yang dapat mengirim.
drop policy if exists "Chat can be read by everyone" on public.chat;
create policy "Chat can be read by everyone"
  on public.chat for select to anon, authenticated using (true);

drop policy if exists "Warga can send chat as themselves" on public.chat;
create policy "Warga can send chat as themselves"
  on public.chat for insert to authenticated
  with check (auth.uid() = user_id);

-- Izinkan Supabase Realtime mengirim perubahan kedua tabel.
do $$
begin
  alter publication supabase_realtime add table public.warga;
exception when duplicate_object then null;
when others then
  if sqlstate <> '42710' then raise; end if;
end $$;

do $$
begin
  alter publication supabase_realtime add table public.chat;
exception when duplicate_object then null;
when others then
  if sqlstate <> '42710' then raise; end if;
end $$;
